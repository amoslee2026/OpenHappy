// module name：generic_ckmux
// 功能概述: 2 选 1 时钟 MUX（RTL 行为实现，等效通用标准单元）
//   S=0 → Z=I0；S=1 → Z=I1（两输入相同则输出该值，S=x 亦然）
// =============================================================================
// version history
//   2026-10-26  OpenHappy Team  自主实现：行为模型 → 手写 RTL 实现
// =============================================================================
`timescale 1ns/1ps

module generic_ckmux(
    input   S                           ,
    input   I0                          ,
    input   I1                          ,
    output  Z
);

    assign Z = S ? I1 : I0;

endmodule
